CREATE SCHEMA IF NOT EXISTS dw;
CREATE SCHEMA IF NOT EXISTS ctl;

CREATE TABLE IF NOT EXISTS ctl.watermark (
    pipeline TEXT PRIMARY KEY,
    last_modified TIMESTAMP NOT NULL DEFAULT '1900-01-01',
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS dw.dim_date (
    date_key INT PRIMARY KEY,
    full_date DATE NOT NULL UNIQUE,
    year SMALLINT NOT NULL,
    quarter SMALLINT NOT NULL,
    month SMALLINT NOT NULL,
    month_name TEXT NOT NULL,
    day SMALLINT NOT NULL
);

CREATE TABLE IF NOT EXISTS dw.dim_product (
    product_key INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id INT NOT NULL UNIQUE,
    product_name TEXT NOT NULL,
    product_number TEXT,
    subcategory TEXT,
    category TEXT,
    standard_cost NUMERIC(19,4),
    list_price NUMERIC(19,4),
    modified_at TIMESTAMP
);

CREATE TABLE IF NOT EXISTS dw.dim_customer (
    customer_key INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id INT NOT NULL UNIQUE,
    customer_name TEXT,
    account_number TEXT,
    modified_at TIMESTAMP
);

CREATE TABLE IF NOT EXISTS dw.dim_territory (
    territory_key INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    territory_id INT NOT NULL UNIQUE,
    territory_name TEXT,
    country_region_code TEXT,
    territory_group TEXT,
    modified_at TIMESTAMP
);

CREATE TABLE IF NOT EXISTS dw.dim_salesperson (
    salesperson_key INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    salesperson_id INT NOT NULL UNIQUE,
    salesperson_name TEXT,
    modified_at TIMESTAMP
);

INSERT INTO dw.dim_salesperson(salesperson_id, salesperson_name)
VALUES (-1, 'Sem vendedor')
ON CONFLICT(salesperson_id) DO NOTHING;

INSERT INTO dw.dim_territory(territory_id, territory_name)
VALUES (-1, 'Não informado')
ON CONFLICT(territory_id) DO NOTHING;

INSERT INTO dw.dim_customer(customer_id, customer_name)
VALUES (-1, 'Não informado')
ON CONFLICT(customer_id) DO NOTHING;

CREATE TABLE IF NOT EXISTS dw.fact_sales (
    sales_order_id INT NOT NULL,
    sales_order_detail_id INT NOT NULL,
    order_date_key INT NOT NULL REFERENCES dw.dim_date(date_key),
    product_key INT NOT NULL REFERENCES dw.dim_product(product_key),
    customer_key INT NOT NULL REFERENCES dw.dim_customer(customer_key),
    territory_key INT NOT NULL REFERENCES dw.dim_territory(territory_key),
    salesperson_key INT NOT NULL REFERENCES dw.dim_salesperson(salesperson_key),
    order_qty SMALLINT NOT NULL,
    unit_price NUMERIC(19,4) NOT NULL,
    unit_price_discount NUMERIC(12,6) NOT NULL,
    gross_amount NUMERIC(19,4) NOT NULL,
    discount_amount NUMERIC(19,4) NOT NULL,
    net_amount NUMERIC(19,4) NOT NULL,
    estimated_cost NUMERIC(19,4),
    shipping_days INT,
    source_modified_at TIMESTAMP NOT NULL,
    PRIMARY KEY(sales_order_id, sales_order_detail_id)
);

CREATE INDEX IF NOT EXISTS ix_fact_orderdate ON dw.fact_sales(order_date_key);
CREATE INDEX IF NOT EXISTS ix_fact_product ON dw.fact_sales(product_key);
CREATE INDEX IF NOT EXISTS ix_fact_customer ON dw.fact_sales(customer_key);
CREATE INDEX IF NOT EXISTS ix_fact_territory ON dw.fact_sales(territory_key);
CREATE INDEX IF NOT EXISTS ix_fact_salesperson ON dw.fact_sales(salesperson_key);
